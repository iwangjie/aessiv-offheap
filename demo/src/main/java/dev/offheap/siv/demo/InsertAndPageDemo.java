package dev.offheap.siv.demo;

import java.nio.file.Files;
import java.nio.file.Path;
import java.security.SecureRandom;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.UUID;

/**
 * Two operations only - insert one row, page through a list - annotated so every line can be traced
 * back to what the database actually stores.
 *
 * <p>Kept deliberately small: the other demo proves the security properties, this one is the
 * application code a team writes on day one.
 */
public final class InsertAndPageDemo {

    private static final String TENANT = "tenant-a";

    public static void main(String[] args) throws Exception {
        Path db = Files.createTempDirectory("page-demo").resolve("app.db");
        System.out.println("db file: " + db);

        try (FieldVault vault = FieldVault.create(1, false);
             Connection c = DriverManager.getConnection("jdbc:sqlite:" + db)) {

            createTable(c);
            String aliceId = insertOneUser(c, vault,
                    "a@x.com", "{{PHONE_2b758266}}", "北京");
            insertOneUser(c, vault, "c@x.com", "{{PHONE_f2b7e8c1}}", "上海");
            insertOneUser(c, vault, "a@x.com", "{{PHONE_7c1a9d33}}", "广州");
            insertOneUser(c, vault, "b@x.com", "{{PHONE_4d8f0a55}}", "深圳");
            insertOneUser(c, vault, "{{EMAIL_1c4m9qt0}}", "{{PHONE_9a3e6b12}}", "杭州");

            dumpRawTable(c);

            findUserByEmail(c, vault, "c@x.com");
            pageThrough(c, vault, 1, 2);
            pageThrough(c, vault, 2, 2);
            pageThrough(c, vault, 3, 2);
            decodeRow(c, vault, aliceId);
        }
    }

    // ------------------------------------------------------------------ schema

    /**
     * The id is TEXT and generated by the application, not AUTOINCREMENT. That is not a preference:
     * a bound column needs the row id in the AAD, so the id has to exist before the INSERT.
     */
    private static void createTable(Connection c) throws SQLException {
        try (Statement st = c.createStatement()) {
            st.execute("CREATE TABLE users ("
                    + "  id        TEXT PRIMARY KEY,"        // random UUID, in the clear
                    + "  tenant    TEXT NOT NULL,"            // in the clear: used in WHERE
                    + "  email_enc BLOB NOT NULL,"            // deterministic: searchable
                    + "  phone_enc BLOB NOT NULL,"            // bound: not searchable
                    + "  city_enc  BLOB NOT NULL,"            // bound: not searchable
                    + "  created_at INTEGER NOT NULL"         // in the clear: used for ORDER BY
                    + ")");
            st.execute("CREATE INDEX users_tenant_email ON users(tenant, email_enc)");
            st.execute("CREATE INDEX users_tenant_created ON users(tenant, created_at, id)");
        }
    }

    // ------------------------------------------------------------------ INSERT

    /**
     * One INSERT. The two encrypted columns are sealed with different modes on purpose:
     * {@code email} passes no row id, so it is deterministic and can be searched; {@code phone} and
     * {@code city} pass the id, so they are bound to this row.
     *
     * @return the id that was used as the row id in the AAD
     */
    private static String insertOneUser(Connection c, FieldVault vault,
                                        String email, String phone, String city)
            throws Exception {
        String id = UUID.randomUUID().toString();

        byte[] emailBlob = vault.seal(TENANT, "users", "email", null, email);
        byte[] phoneBlob = vault.seal(TENANT, "users", "phone", id, phone);
        byte[] cityBlob = vault.seal(TENANT, "users", "city", id, city);

        try (PreparedStatement ps = c.prepareStatement(
                "INSERT INTO users (id, tenant, email_enc, phone_enc, city_enc, created_at)"
                        + " VALUES (?,?,?,?,?,?)")) {
            ps.setString(1, id);
            ps.setString(2, TENANT);
            ps.setBytes(3, emailBlob);
            ps.setBytes(4, phoneBlob);
            ps.setBytes(5, cityBlob);
            ps.setLong(6, System.nanoTime() / 1000L);
            ps.executeUpdate();
        }

        System.out.printf("%nINSERT %s: email=%d B phone=%d B city=%d B%n",
                id.substring(0, 8), emailBlob.length, phoneBlob.length, cityBlob.length);
        return id;
    }

    // ------------------------------------------------------------------ SELECT by value

    /**
     * "Find the user with this e-mail". Works because the email column is deterministic: sealing the
     * same value again produces the same bytes, so the database can compare them with its own index.
     * No decryption happens on the server, and nothing is decrypted client-side either.
     */
    private static void findUserByEmail(Connection c, FieldVault vault, String email)
            throws Exception {
        System.out.println("\n== SELECT by encrypted value: " + email + " ==");

        byte[] probe = vault.seal(TENANT, "users", "email", null, email);

        try (PreparedStatement ps = c.prepareStatement(
                "SELECT id, city_enc FROM users WHERE tenant = ? AND email_enc = ?")) {
            ps.setString(1, TENANT);
            ps.setBytes(2, probe);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    String id = rs.getString(1);
                    String city = vault.open(TENANT, "users", "city", id, rs.getBytes(2));
                    System.out.println("  found " + id.substring(0, 8) + " city=" + city);
                }
            }
        }
    }

    // ------------------------------------------------------------------ SELECT page

    /**
     * Pagination never filters on ciphertext, because it cannot: ciphertext ordering is random. The
     * page is selected on the cleartext columns - tenant and created_at - and only the rows that
     * actually land on the page are decrypted.
     *
     * <p>Two consequences worth knowing: OFFSET pagination re-scans, so use keyset pagination for
     * deep pages; and the row count is visible to the database, which is unavoidable.
     */
    private static void pageThrough(Connection c, FieldVault vault, int page, int size)
            throws Exception {
        int offset = (page - 1) * size;

        try (PreparedStatement ps = c.prepareStatement(
                "SELECT id, email_enc, city_enc FROM users"
                        + " WHERE tenant = ?"
                        + " ORDER BY created_at, id"
                        + " LIMIT ? OFFSET ?")) {
            ps.setString(1, TENANT);
            ps.setInt(2, size);
            ps.setInt(3, offset);

            System.out.printf("%n== page %d (size %d, offset %d) ==%n", page, size, offset);
            long start = System.nanoTime();
            try (ResultSet rs = ps.executeQuery()) {
                int n = 0;
                while (rs.next()) {
                    n++;
                    String id = rs.getString(1);
                    String email = vault.open(TENANT, "users", "email", null, rs.getBytes(2));
                    String city = vault.open(TENANT, "users", "city", id, rs.getBytes(3));
                    System.out.printf("  %s  %-22s %s%n", id.substring(0, 8), email, city);
                }
                System.out.printf("  %d rows decrypted in %.2f ms%n", n,
                        (System.nanoTime() - start) / 1e6);
            }
        }
    }

    /** Total pages needs a COUNT, which works only on cleartext predicates - there is nothing else. */
    private static void decodeRow(Connection c, FieldVault vault, String id) throws Exception {
        System.out.println("\n== full row decode ==");
        try (PreparedStatement ps = c.prepareStatement(
                "SELECT email_enc, phone_enc, city_enc FROM users WHERE id = ?")) {
            ps.setString(1, id);
            try (ResultSet rs = ps.executeQuery()) {
                rs.next();
                System.out.println("  email = " + vault.open(TENANT, "users", "email", null,
                        rs.getBytes(1)));
                System.out.println("  phone = " + vault.open(TENANT, "users", "phone", id,
                        rs.getBytes(2)));
                System.out.println("  city  = " + vault.open(TENANT, "users", "city", id,
                        rs.getBytes(3)));
            }
        }
    }

    /** What the table really holds: hex, so the difference between a blob and a value is visible. */
    private static void dumpRawTable(Connection c) throws SQLException {
        System.out.println("\n== raw table contents ==");
        try (Statement st = c.createStatement();
             ResultSet rs = st.executeQuery(
                     "SELECT id, tenant, email_enc, city_enc FROM users ORDER BY created_at")) {
            while (rs.next()) {
                System.out.printf("  %s %s email=%s city=%s%n",
                        rs.getString(1).substring(0, 8), rs.getString(2),
                        hexHead(rs.getBytes(3)), hexHead(rs.getBytes(4)));
            }
        }
    }

    private static String hexHead(byte[] raw) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < Math.min(raw.length, 8); i++) {
            sb.append(String.format("%02x", raw[i]));
        }
        return sb.append("..(").append(raw.length).append("B)").toString();
    }
}
